-- Flyway V1: schema in force before Flyway was introduced (formerly docker-init.sql).
-- The DDL below is identical to that file; only BEGIN/COMMIT were removed because
-- Flyway runs each PostgreSQL migration in its own transaction.
-- Never edit this file once released: Flyway validates its checksum. Add V2+ instead.
-- Existing databases are adopted with a baseline at version 1 (see DATABASE_MIGRATIONS.md),
-- guarded by beforeBaseline.sql; this script is then not executed on them.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    enabled boolean NOT NULL,
    verification_token varchar(255),
    reset_token varchar(255),
    reset_token_expiry timestamp(6),
    created_at timestamp(6)
);
CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    color varchar(7),
    icon varchar(50),
    description text,
    user_id bigint
);

CREATE TABLE transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description varchar(200) NOT NULL,
    amount numeric(15,2) NOT NULL,
    type varchar(255) NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    date date NOT NULL,
    notes varchar(500),
    category_id bigint REFERENCES categories(id),
    user_id bigint,
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE TABLE study_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    subject varchar(255),
    estimated_time varchar(255),
    done boolean NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamp(6)
);

CREATE TABLE planning_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description varchar(255),
    type varchar(255) NOT NULL,
    location varchar(255),
    duration varchar(255),
    date date NOT NULL,
    time varchar(255),
    done boolean NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamp(6)
);

CREATE TABLE goals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description varchar(255),
    category varchar(255) NOT NULL,
    progress integer NOT NULL,
    target integer NOT NULL,
    unit varchar(255),
    color varchar(255),
    deadline date,
    completed boolean NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamp(6)
);

CREATE TABLE fitness_workouts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    type varchar(255) NOT NULL,
    duration integer,
    calories integer,
    date date,
    notes varchar(255),
    user_id bigint NOT NULL,
    created_at timestamp(6)
);
